clear
close all
clc

%% File names

pbm_file = 'softsphere_meshsize_PBM_normal_allfreq.csv';
ubm_file = 'softsphere_numberelements_UBM_lambda_6_allfreq.csv';

output_file = fullfile(pwd, ...
    'softsphere_meshvolume_PBM_vs_UBM_3D_planes.png');

%% Frequency sweep

frequency_min_hz = 50;
frequency_max_hz = 70000;
num_frequencies  = 32;

% The CSV files contain 320 numerical rows:
% 32 frequency-specific histograms × 10 bins per histogram.
%
% COMSOL did not export frequency as a separate column, so reconstruct
% the logarithmic sweep, including 50 and 70,000 Hz.
frequency_hz = logspace( ...
    log10(frequency_min_hz), ...
    log10(frequency_max_hz), ...
    num_frequencies);

%% Plot formatting

pbm_color = [0.00 0.45 0.74];  % blue
ubm_color = [0.85 0.33 0.10];  % orange

% Plane opacity increases with frequency.
minimum_opacity = 0.15;
maximum_opacity = 0.15;

% Line formatting
plane_edge_width  = 3.5;
legend_line_width = 7.0;

% Font formatting
axis_font_size   = 28;
label_font_size  = 34;
title_font_size  = 38;
legend_font_size = 27;
axis_line_width  = 3.5;

%% Import and reshape COMSOL histogram exports

[pbm_size_mm, pbm_volume_mm3] = read_comsol_histograms( ...
    pbm_file, num_frequencies);

[ubm_size_mm, ubm_volume_mm3] = read_comsol_histograms( ...
    ubm_file, num_frequencies);

num_pbm_bins = size(pbm_size_mm, 1);
num_ubm_bins = size(ubm_size_mm, 1);

fprintf('PBM: %d frequencies × %d histogram bins\n', ...
    num_frequencies, num_pbm_bins);

fprintf('UBM: %d frequencies × %d histogram bins\n', ...
    num_frequencies, num_ubm_bins);

%% Map frequency to plane opacity

log_frequency = log10(frequency_hz);

frequency_fraction = ...
    (log_frequency - min(log_frequency)) ./ ...
    (max(log_frequency) - min(log_frequency));

plane_opacity = minimum_opacity + ...
    (maximum_opacity - minimum_opacity) .* ...
    frequency_fraction;

%% Create figure

fig = figure( ...
    'Color', 'w', ...
    'Position', [50 40 1550 1050]);

ax = axes(fig);
hold(ax, 'on');

%% Plot 3D histogram planes

for index = 1:num_frequencies

    current_frequency = frequency_hz(index);
    current_opacity   = plane_opacity(index);

    %% User-defined mesh plane

    ubm_y = ubm_size_mm(:, index);
    ubm_z = ubm_volume_mm3(:, index);
    ubm_x = repmat( ...
        current_frequency, numel(ubm_y) + 2, 1);

    fill3(ax, ...
        ubm_x, ...
        [ubm_y(1); ubm_y; ubm_y(end)], ...
        [0; ubm_z; 0], ...
        ubm_color, ...
        'FaceAlpha', current_opacity, ...
        'EdgeColor', ubm_color, ...
        'EdgeAlpha', min(0.3), ...
        'LineStyle', '-', ...
        'LineWidth', plane_edge_width, ...
        'HandleVisibility', 'off');

    %% Physics-controlled mesh plane

    pbm_y = pbm_size_mm(:, index);
    pbm_z = pbm_volume_mm3(:, index);
    pbm_x = repmat( ...
        current_frequency, numel(pbm_y) + 2, 1);

    fill3(ax, ...
        pbm_x, ...
        [pbm_y(1); pbm_y; pbm_y(end)], ...
        [0; pbm_z; 0], ...
        pbm_color, ...
        'FaceAlpha', current_opacity, ...
        'EdgeColor', pbm_color, ...
        'EdgeAlpha', min(0.3), ...
        'LineStyle', '-', ...
        'LineWidth', plane_edge_width, ...
        'HandleVisibility', 'off');
end

%% Legend handles

h_pbm = plot3(ax, nan, nan, nan, ...
    '-', ...
    'Color', pbm_color, ...
    'LineWidth', legend_line_width, ...
    'DisplayName', ...
    'Physics-controlled mesh (Normal)');

h_ubm = plot3(ax, nan, nan, nan, ...
    '--', ...
    'Color', ubm_color, ...
    'LineWidth', legend_line_width, ...
    'DisplayName', ...
    'User-defined mesh (\lambda/6)');

%% Axes formatting

set(ax, ...
    'XScale', 'log', ...
    'FontSize', axis_font_size, ...
    'FontWeight', 'bold', ...
    'LineWidth', axis_line_width, ...
    'TickLength', [0.015 0.015], ...
    'TickDir', 'out', ...
    'Box', 'on');

xlabel(ax, ...
    'Frequency (Hz)', ...
    'FontSize', label_font_size, ...
    'FontWeight', 'bold');

ylabel(ax, ...
    'Element size (mm)', ...
    'FontSize', label_font_size, ...
    'FontWeight', 'bold');

zlabel(ax, ...
    'Mesh volume per bin (mm^3)', ...
    'FontSize', label_font_size, ...
    'FontWeight', 'bold');

title(ax, ...
    'Element-size distributions across frequency', ...
    'FontSize', title_font_size, ...
    'FontWeight', 'bold');


%% Axis limits

xlim(ax, [frequency_min_hz, frequency_max_hz]);

all_element_sizes = [ ...
    pbm_size_mm(:); ...
    ubm_size_mm(:)];

all_mesh_volumes = [ ...
    pbm_volume_mm3(:); ...
    ubm_volume_mm3(:)];

ylim(ax, [ ...
    min(all_element_sizes), ...
    max(all_element_sizes)]);

maximum_volume = max(all_mesh_volumes);

if maximum_volume > 0
    zlim(ax, [0, 1.05 * maximum_volume]);
end

%% Frequency ticks

frequency_ticks = [ ...
    50, 100, 500, 1000, ...
    5000, 10000, 50000, 70000];

frequency_tick_labels = { ...
    '50', '100', '500', '1k', ...
    '5k', '10k', '50k', '70k'};

set(ax, ...
    'XTick', frequency_ticks, ...
    'XTickLabel', frequency_tick_labels);

%% Legend

legend(ax, [h_pbm, h_ubm], ...
    'Location', 'northeast', ...
    'FontSize', legend_font_size, ...
    'FontWeight', 'bold', ...
    'Box', 'on');

%% Grid and view

grid(ax, 'on');

ax.GridAlpha      = 0.25;
ax.MinorGridAlpha = 0.15;
ax.SortMethod     = 'childorder';

view(ax, 46, 28);

%% Export figure

exportgraphics(fig, output_file, ...
    'Resolution', 300);

fprintf('Figure saved to:\n%s\n', output_file);

%% Local function

function [element_size_mm, mesh_volume_mm3] = ...
    read_comsol_histograms(file_name, num_frequencies)

    data = readmatrix(file_name, ...
        'CommentStyle', '%');

    if size(data, 2) < 2
        error([ ...
            'File %s must contain at least two ', ...
            'numerical columns.'], ...
            file_name);
    end

    % Remove headers, blank rows, and nonnumeric entries.
    valid_rows = all(isfinite(data(:, 1:2)), 2);
    data = data(valid_rows, 1:2);

    num_rows = size(data, 1);

    if mod(num_rows, num_frequencies) ~= 0
        error([ ...
            'File %s contains %d valid numerical rows. ', ...
            'These rows cannot be divided evenly among ', ...
            '%d frequencies.'], ...
            file_name, num_rows, num_frequencies);
    end

    num_bins = num_rows / num_frequencies;

    % COMSOL exports the frequency-specific histograms sequentially:
    %
    % frequency 1: bins 1–N
    % frequency 2: bins 1–N
    % ...
    %
    % After reshaping:
    % rows    = element-size bins
    % columns = frequencies
    element_size_mm = reshape( ...
        data(:, 1), ...
        num_bins, ...
        num_frequencies);

    % COMSOL exported histogram volumes in m^3.
    % Convert m^3 to mm^3 using 1 m^3 = 10^9 mm^3.
    mesh_volume_mm3 = reshape( ...
        data(:, 2) .* 1e9, ...
        num_bins, ...
        num_frequencies);

    % Confirm that the element-size bins increase within each histogram.
    if any(any(diff(element_size_mm, 1, 1) <= 0))
        error([ ...
            'Element-size bins are not strictly increasing ', ...
            'within every histogram in %s. Check the CSV ', ...
            'ordering or specified number of frequencies.'], ...
            file_name);
    end

    % Histogram volumes cannot be negative.
    if any(mesh_volume_mm3(:) < 0)
        error( ...
            'Negative histogram volumes were detected in %s.', ...
            file_name);
    end
end