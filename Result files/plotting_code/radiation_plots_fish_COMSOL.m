clear
close all
clc

%% File names

azimuth_file = ...
    'midshipman_radiationpattern_azimuthal.csv';

vertical_file = ...
    'midshipman_radiationpattern_vertical.csv';

azimuth_output = fullfile( ...
    pwd, 'midshipman_radiationpattern_azimuthal.png');

vertical_output = fullfile( ...
    pwd, 'midshipman_radiationpattern_vertical.png');

%% Plot formatting

line_width = 4;
marker_size = 9;
marker_step = 10;

axis_font_size   = 21;
title_font_size  = 28;
legend_font_size = 20;
label_font_size  = 21;
axis_line_width  = 2;

% Frequency colors
color_38kHz = [0.00 0.45 0.74];  % Blue
color_70kHz = [0.85 0.10 0.10];  % Red

% Absolute target-strength limits
radial_min  = -60;
radial_max  = -35;
radial_step = 5;

%% Import azimuthal data

azimuth_data = readmatrix(azimuth_file);

if size(azimuth_data, 2) < 2
    error(['The azimuthal CSV must contain two columns: ', ...
        'angle and target strength.'])
end

azimuth_data = azimuth_data( ...
    all(isfinite(azimuth_data(:,1:2)), 2), 1:2);

if isempty(azimuth_data)
    error('No valid data were found in the azimuthal CSV.')
end

theta_azimuth = azimuth_data(:,1);
TS_azimuth    = azimuth_data(:,2);

%% Import vertical data

vertical_data = readmatrix(vertical_file);

if size(vertical_data, 2) < 2
    error(['The vertical CSV must contain two columns: ', ...
        'angle and target strength.'])
end

vertical_data = vertical_data( ...
    all(isfinite(vertical_data(:,1:2)), 2), 1:2);

if isempty(vertical_data)
    error('No valid data were found in the vertical CSV.')
end

theta_vertical = vertical_data(:,1);
TS_vertical    = vertical_data(:,2);

%% Find where the angle resets for the second frequency

azimuth_reset = find(diff(theta_azimuth) < 0);
vertical_reset = find(diff(theta_vertical) < 0);

if numel(azimuth_reset) ~= 1
    error(['Expected exactly one angle reset in the azimuthal ', ...
        'CSV, but found %d.'], numel(azimuth_reset))
end

if numel(vertical_reset) ~= 1
    error(['Expected exactly one angle reset in the vertical ', ...
        'CSV, but found %d.'], numel(vertical_reset))
end

azimuth_split = azimuth_reset + 1;
vertical_split = vertical_reset + 1;

%% Separate the 38 kHz and 70 kHz azimuthal data

theta_azimuth_38 = ...
    theta_azimuth(1:azimuth_split-1);

TS_azimuth_38 = ...
    TS_azimuth(1:azimuth_split-1);

theta_azimuth_70 = ...
    theta_azimuth(azimuth_split:end);

TS_azimuth_70 = ...
    TS_azimuth(azimuth_split:end);

%% Separate the 38 kHz and 70 kHz vertical data

theta_vertical_38 = ...
    theta_vertical(1:vertical_split-1);

TS_vertical_38 = ...
    TS_vertical(1:vertical_split-1);

theta_vertical_70 = ...
    theta_vertical(vertical_split:end);

TS_vertical_70 = ...
    TS_vertical(vertical_split:end);

%% Convert dB values to nonnegative polar radii

% -60 dB corresponds to the center.
% 0 dB corresponds to the outer circle.

r_azimuth_38 = max(TS_azimuth_38 - radial_min, 0);
r_azimuth_70 = max(TS_azimuth_70 - radial_min, 0);

r_vertical_38 = max(TS_vertical_38 - radial_min, 0);
r_vertical_70 = max(TS_vertical_70 - radial_min, 0);

%% Radial tick positions and labels

radial_values = radial_min:radial_step:radial_max;
radial_positions = radial_values - radial_min;
radial_labels = string(radial_values);

%% Azimuthal radiation pattern

fig_azimuth = figure( ...
    'Color', 'w', ...
    'Position', [100 100 1000 850]);

h_azimuth_38 = polarplot( ...
    theta_azimuth_38, ...
    r_azimuth_38, ...
    '-o', ...
    'Color', color_38kHz, ...
    'LineWidth', line_width, ...
    'MarkerIndices', ...
        1:marker_step:numel(theta_azimuth_38), ...
    'MarkerSize', marker_size, ...
    'MarkerEdgeColor', color_38kHz, ...
    'MarkerFaceColor', 'none', ...
    'DisplayName', '38 kHz');

hold on

h_azimuth_70 = polarplot( ...
    theta_azimuth_70, ...
    r_azimuth_70, ...
    '-s', ...
    'Color', color_70kHz, ...
    'LineWidth', line_width, ...
    'MarkerIndices', ...
        1:marker_step:numel(theta_azimuth_70), ...
    'MarkerSize', marker_size, ...
    'MarkerEdgeColor', color_70kHz, ...
    'MarkerFaceColor', 'none', ...
    'DisplayName', '70 kHz');

pax = gca;

% Angular-axis formatting
pax.ThetaZeroLocation = 'right';
pax.ThetaDir = 'counterclockwise';
pax.ThetaTick = 0:30:330;
pax.ThetaTickLabel = compose( ...
    '%d°', pax.ThetaTick);

% Radial-axis formatting
pax.RLim = [0 radial_max-radial_min];
pax.RTick = radial_positions;
pax.RTickLabel = radial_labels;

% Move radial tick numbers away from the forward-facing pattern
pax.RAxisLocation = 135;

% Remove the default radial label from inside the plot
pax.RAxis.Label.String = '';

% General formatting
pax.FontSize = axis_font_size;
pax.FontWeight = 'bold';
pax.LineWidth = axis_line_width;
pax.GridAlpha = 0.35;
pax.MinorGridAlpha = 0.20;

% Make room below the plot for the radial-axis label
pax.Position = [0.10 0.15 0.80 0.72];

title( ...
    'Midshipman Azimuthal Radiation Pattern', ...
    'FontSize', title_font_size, ...
    'FontWeight', 'bold');

legend( ...
    [h_azimuth_38 h_azimuth_70], ...
    {'38 kHz', '70 kHz'}, ...
    'Location', 'best', ...
    'FontSize', legend_font_size, ...
    'FontWeight', 'bold');

% Place target-strength label below the polar plot
annotation( ...
    fig_azimuth, ...
    'textbox', ...
    [0.20 0.025 0.60 0.055], ...
    'String', 'Target strength (dB re 1 m)', ...
    'FontSize', label_font_size, ...
    'FontWeight', 'bold', ...
    'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'middle', ...
    'EdgeColor', 'none');

exportgraphics( ...
    fig_azimuth, ...
    azimuth_output, ...
    'Resolution', 300);

%% Vertical radiation pattern

fig_vertical = figure( ...
    'Color', 'w', ...
    'Position', [1050 100 1000 850]);

h_vertical_38 = polarplot( ...
    theta_vertical_38, ...
    r_vertical_38, ...
    '-o', ...
    'Color', color_38kHz, ...
    'LineWidth', line_width, ...
    'MarkerIndices', ...
        1:marker_step:numel(theta_vertical_38), ...
    'MarkerSize', marker_size, ...
    'MarkerEdgeColor', color_38kHz, ...
    'MarkerFaceColor', 'none', ...
    'DisplayName', '38 kHz');

hold on

h_vertical_70 = polarplot( ...
    theta_vertical_70, ...
    r_vertical_70, ...
    '-s', ...
    'Color', color_70kHz, ...
    'LineWidth', line_width, ...
    'MarkerIndices', ...
        1:marker_step:numel(theta_vertical_70), ...
    'MarkerSize', marker_size, ...
    'MarkerEdgeColor', color_70kHz, ...
    'MarkerFaceColor', 'none', ...
    'DisplayName', '70 kHz');

pax = gca;

% Angular-axis formatting
pax.ThetaZeroLocation = 'right';
pax.ThetaDir = 'counterclockwise';
pax.ThetaTick = 0:30:330;
pax.ThetaTickLabel = compose( ...
    '%d°', pax.ThetaTick);

% Radial-axis formatting
pax.RLim = [0 radial_max-radial_min];
pax.RTick = radial_positions;
pax.RTickLabel = radial_labels;

% Move radial tick numbers away from the forward-facing pattern
pax.RAxisLocation = 135;

% Remove the default radial label from inside the plot
pax.RAxis.Label.String = '';

% General formatting
pax.FontSize = axis_font_size;
pax.FontWeight = 'bold';
pax.LineWidth = axis_line_width;
pax.GridAlpha = 0.35;
pax.MinorGridAlpha = 0.20;

% Make room below the plot for the radial-axis label
pax.Position = [0.10 0.15 0.80 0.72];

title( ...
    'Midshipman Vertical Radiation Pattern', ...
    'FontSize', title_font_size, ...
    'FontWeight', 'bold');

legend( ...
    [h_vertical_38 h_vertical_70], ...
    {'38 kHz', '70 kHz'}, ...
    'Location', 'best', ...
    'FontSize', legend_font_size, ...
    'FontWeight', 'bold');

% Place target-strength label below the polar plot
annotation( ...
    fig_vertical, ...
    'textbox', ...
    [0.20 0.025 0.60 0.055], ...
    'String', 'Target strength (dB re 1 m)', ...
    'FontSize', label_font_size, ...
    'FontWeight', 'bold', ...
    'HorizontalAlignment', 'center', ...
    'VerticalAlignment', 'middle', ...
    'EdgeColor', 'none');

exportgraphics( ...
    fig_vertical, ...
    vertical_output, ...
    'Resolution', 300);

%% Confirm output locations

fprintf('Azimuthal figure saved to:\n%s\n', ...
    azimuth_output);

fprintf('Vertical figure saved to:\n%s\n', ...
    vertical_output);